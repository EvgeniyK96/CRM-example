class Command(BaseCommand):
    help = "Заполняет справочники каталога: единицы, категории, сырьё, продукцию, поставщиков"

    @transaction.atomic
    def handle(self, *args, **options):
        call_command("seed_hr", stdout=self.stdout)
        units = {code: Unit.objects.get_or_create(code=code, defaults={"name": name})[0] for code, name in UNITS}

        def category(name, kind):
            return Category.objects.get_or_create(name=name, kind=kind)[0]

        for code, name, cat, unit, shelf, min_stock in RAW:
            Item.objects.get_or_create(code=code, defaults={
                "kind": ItemKind.RAW, "name": name, "category": category(cat, ItemKind.RAW),
                "unit": units[unit], "shelf_life_days": shelf, "min_stock": min_stock,
            })
        for code, name, cat, unit, shelf, dep, price in PRODUCTS:
            Item.objects.get_or_create(code=code, defaults={
                "kind": ItemKind.PRODUCT, "name": name, "category": category(cat, ItemKind.PRODUCT),
                "unit": units[unit], "shelf_life_days": shelf, "sale_price": price,
                "department": Department.objects.get(name=dep),
            })
        for name, note, phone in SUPPLIERS:
            Supplier.objects.get_or_create(name=name, defaults={"note": note, "phone": phone})
        self.stdout.write(self.style.SUCCESS("Каталог заполнен"))
